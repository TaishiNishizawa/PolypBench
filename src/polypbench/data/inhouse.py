"""Loader for the in-house colonoscopy video dataset.

Four 15 s clips with sparse annotations (one every 15 frames). The frame ->
mask mapping lives in configs/datasets/inhouse.yaml, generated by
scripts/build_inhouse_manifest.py.

Usage:
    from polypbench.data.inhouse import load_inhouse
    dataset = load_inhouse()
"""

import yaml

from polypbench.data.base import Dataset, VideoFileSequence
from polypbench.paths import CONFIG_DIR, DATA_ROOT

CONFIG_PATH = CONFIG_DIR / "datasets" / "inhouse.yaml"


def load_inhouse():
    """Build the in-house Dataset from configs/datasets/inhouse.yaml."""
    with open(CONFIG_PATH) as f:
        config = yaml.safe_load(f)

    root = DATA_ROOT / config["root"]
    masks_dir = root / config["masks_dir"]

    sequences = []
    for name, seq in config["sequences"].items():
        annotations = {int(idx): masks_dir / fname for idx, fname in seq["annotations"].items()}
        sequences.append(VideoFileSequence(
            name=name,
            video_path=root / seq["video"],
            n_frames=seq["n_frames"],
            fps=seq["fps"],
            annotations=annotations,
        ))

    return Dataset(config["name"], sequences)
